const { chromium } = require('@playwright/test');
const { spawn } = require('node:child_process');
const { readFileSync, writeFileSync } = require('node:fs');
const net = require('node:net');
const assert = require('node:assert/strict');
const freePort = () => new Promise(resolve => { const s = net.createServer(); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => resolve(p)); }); });
(async () => {
  const port = await freePort(), url = `http://127.0.0.1:${port}`;
  const server = spawn('python3', ['-c', readFileSync('tests/serve.py', 'utf8').replace('8765', String(port))], { stdio: 'ignore' });
  let browser;
  try {
    for (let i = 0; i < 60; i++) { try { if ((await fetch(url)).ok) break; } catch {} await new Promise(r => setTimeout(r, 100)); }
    browser = await chromium.launch({ args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(url); await page.waitForFunction(() => App.workcellUI?.activeRobotName);
    await page.locator('#start-programming').click();
    await page.locator('#lesson-teach').click();
    await page.waitForFunction(() => !!App.workcellUI.teachingStart);
    assert.equal(await page.locator('#program-source-details').getAttribute('open'), null);
    assert.equal(await page.evaluate(() => App.workcellUI.currentJacobianHealth.status), 'regular');
    const state = () => page.evaluate(() => App.workcellUI.teachingStart.names.map(n => robotjointcollection.findWhere({ name: n }).theta));
    const start = await state();
    await page.screenshot({ path: 'notes/artifacts/learning_start.png' });
    await page.locator('#pendant-teach-joints').click();
    await page.locator('[data-pendant-axis="0"][data-pendant-sign="1"]').click();
    const end = await state(); assert.notDeepEqual(start, end);
    await page.locator('#pendant-teach-joints').click();
    await page.locator('#lesson-return').click(); assert.deepEqual(await state(), start);
    await page.locator('#program-plan').click();
    await page.waitForFunction(() => !!App.workcellUI.plan || document.getElementById('program-status').classList.contains('text-danger'));
    const planned = await page.evaluate(() => ({ first: App.workcellUI.plan?.samples[0].q, last: App.workcellUI.plan?.samples.at(-1).q, status: document.getElementById('program-status').textContent }));
    assert.deepEqual(planned.first, start, planned.status);
    planned.last.forEach((q,i) => assert.ok(Math.abs(q-end[i]) < 1e-4));
    await page.locator('#program-play').click();
    await page.waitForFunction(() => App.workcellUI.player.state === 'finished');
    (await state()).forEach((q,i) => assert.ok(Math.abs(q-end[i]) < 1e-4));
    assert.match(await page.locator('#program-lifecycle').textContent(), /Finished/);
    await page.locator('#program-reset').click();
    await page.evaluate(() => { const ui = App.workcellUI; ui.player.seek(ui.plan.duration / 2); });
    const middle = await state();
    await page.locator('#program-source-details summary').click();
    await page.locator('#program-source').fill((await page.locator('#program-source').inputValue()) + '\n# edited');
    assert.deepEqual(await state(), middle, 'editing must preserve displayed robot pose');
    assert.equal(await page.evaluate(() => !!App.workcellUI.plan), false);
    assert.match(await page.locator('#program-lifecycle').textContent(), /No planned path/);
    await page.locator('#lesson-singularity-exercise > summary').click();
    await page.locator('#lesson-singularity').click();
    assert.equal(await page.evaluate(() => App.workcellUI.currentJacobianHealth.status), 'rank_deficient');
    await page.locator('#pendant-frame').selectOption('world');
    const singular = await state();
    await page.locator('[data-pendant-axis="0"][data-pendant-sign="1"]').click();
    assert.deepEqual(await state(), singular);
    assert.match(await page.locator('#pendant-status').textContent(), /unchanged/);
    assert.equal(await page.locator('#pendant-recover-joint').isVisible(), true);
    assert.match(await page.locator('#pendant-result').textContent(), /Residual:/);
    await page.screenshot({ path: 'notes/artifacts/learning_singular_recovery.png' });
    await page.locator('#pendant-recover-joint').click();
    assert.equal(await page.locator('#pendant-frame').inputValue(), 'joint');
    assert.doesNotMatch(await page.locator('#program-status').textContent(), /Jog blocked/);
    await page.locator('[data-pendant-axis="4"][data-pendant-sign="1"]').click();
    assert.notDeepEqual(await state(), singular);
    await page.locator('#lesson-return').click();
    await page.evaluate(() => { document.getElementById('panel-program').scrollTop = 0; });
    await page.screenshot({ path: 'notes/artifacts/learning_workflow.png' });
    assert.deepEqual(errors, []);
    writeFileSync('notes/artifacts/learning_workflow.json', JSON.stringify({ start, end, planned, middle, errors }, null, 2));
    console.log(JSON.stringify({ status: 'passed' }));
  } finally { await browser?.close(); server.kill(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
